import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
const dist=path.resolve('dist');
const read=file=>fs.readFileSync(path.join(dist,file),'utf8');
const manifest=JSON.parse(read('manifest.webmanifest'));
assert.equal(manifest.display,'standalone');
assert.equal(manifest.icons.length,2);
assert.equal(manifest.theme_color,'#1F2429');
for(const f of ['index.html','sw.js','pwa-192.png','pwa-512.png','manifest.webmanifest'])assert.ok(fs.existsSync(path.join(dist,f)),f);
const html=read('index.html');
assert.match(html,/manifest\.webmanifest/);
const sw=read('sw.js');
assert.match(sw,/addAll\(FILES\)/);
assert.match(sw,/api\/.*s3\//);
const css=fs.readdirSync(path.join(dist,'assets')).filter(f=>f.endsWith('.css')).map(f=>read('assets/'+f)).join('\n');
assert.ok(css.includes('575.98px'), 'phone breakpoint');
assert.ok(css.includes('991.98px'), 'tablet breakpoint');
console.log('LAB7 static checks OK: manifest, SW, offline precache, 192/512 icons, responsive CSS.');
console.log('mode:',manifest.scope === '/'?'LAN':'GitHub Pages', 'base:',manifest.scope);
